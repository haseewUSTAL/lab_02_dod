package ru.university.lab2;

import java.util.Scanner;

/**
 * Задание № 8 — Консольное меню
 * (Цикл do-while, switch-выражение со стрелочным синтаксисом, текстовые блоки и защита от ввода)
 */
public class Task08Menu {

    public void run() {
        Scanner scanner = new Scanner(System.in);
        boolean running = true;

        do {
            printHelpMenu();
            System.out.print("Введите пункт меню: ");

            // Защита от ввода букв вместо чисел
            if (!scanner.hasNextInt()) {
                System.out.println("\n[Ошибка] Введено не число! Пожалуйста, используйте цифры.\n");
                scanner.next(); // Очищаем некорректный токен из буфера
                continue;
            }

            int choice = scanner.nextInt();

            // switch как выражение со стрелочным синтаксисом (Java 14+)
            String actionResult = switch (choice) {
                case 0 -> {
                    running = false;
                    yield "Выход из программы. До свидания!";
                }
                case 1 -> "Выбрано Задание № 1: Целочисленные ловушки.";
                case 2 -> "Выбрано Задание № 2: Вещественная арифметика.";
                case 3 -> "Выбрано Задание № 3: Побитовые операции.";
                case 4 -> "Выбрано Задание № 4: Обработка текста.";
                case 5 -> "Выбрано Задание № 5: Одномерные массивы.";
                case 6 -> "Выбрано Задание № 6: Многомерные массивы.";
                case 7 -> "Выбрано Задание № 7: Методы и varargs.";
                case 8 -> "Выбрано Задание № 8: Консольное меню.";
                default -> "Ошибка: такого пункта меню не существует. Выберите от 0 до 8.";
            };

            System.out.println("\n" + actionResult + "\n");

        } while (running);
    }

    // Текстовый блок для вывода справки по программе
    private void printHelpMenu() {
        String menuBlock = """
                ========================================
                        ГЛАВНОЕ МЕНЮ ЛАБОРАТОРНОЙ
                ========================================
                 1 - Задание № 1 (Целочисленные ловушки)
                 2 - Задание № 2 (Вещественная арифметика)
                 3 - Задание № 3 (Побитовые операции)
                 4 - Задание № 4 (Обработка текста)
                 5 - Задание № 5 (Одномерные массивы)
                 6 - Задание № 6 (Многомерные массивы)
                 7 - Задание № 7 (Методы и передача аргументов)
                 8 - Задание № 8 (Показать это меню)
                 0 - Выход
                ========================================
                """;
        System.out.println(menuBlock);
    }
}